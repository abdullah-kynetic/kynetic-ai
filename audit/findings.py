SEVERITY_RANK = {"high": 0, "medium": 1, "low": 2}


def _from_items(check: str, data: dict[str, Any], tool: str, source: str) -> list[Finding]:
    out: list[Finding] = []
    for item in data.get("items", []):
        if item["status"] not in ("fail", "warn"):
            continue
        key = "after_hours_op" if (check == "operations" and item["key"] == "after_hours") else item["key"]
        rule = RULES.get(key)
        if not rule:
            continue
        category, severity, title, why, fix, service = rule
        if item["status"] == "warn":
            severity = {"high": "medium", "medium": "low", "low": "low"}[severity]
        observed = f"{item['label']}: {item['value']}" if item.get("value") else item["label"]
        out.append(Finding(f"{check}.{item['key']}", category, severity, title, observed, why, fix, service, tool, source))
    return out


def build_findings(checks: dict[str, dict[str, Any]], answers: dict[str, str], operations_items: list) -> list[Finding]:
    out: list[Finding] = []
    for name in ("seo", "capture", "trust"):
        check = checks.get(name) or {}
        if check.get("status") == "ok":
            sources = check.get("sources") or []
            out += _from_items(name, check["data"], check.get("tool", name), sources[0] if sources else "")

    speed = checks.get("speed") or {}
    if speed.get("status") == "ok":
        mobile = speed["data"].get("mobile") or {}
        perf = mobile.get("performance_score")
        lcp = ((mobile.get("metrics") or {}).get("largest-contentful-paint") or {}).get("value")
        if perf is not None and perf < 90:
            top = ", ".join(o["title"].lower() for o in (mobile.get("opportunities") or [])[:3])
            out.append(Finding("speed.mobile", "speed", "high" if perf < 50 else "medium" if perf < 75 else "low",
                               "The site is slow on phones",
                               f"Mobile performance score {perf}/100" + (f"; main content shows after {lcp}" if lcp else ""),
                               "Slow pages lose visitors before they see your phone number. Speed also affects ranking.",
                               "Fix the biggest delays first" + (f": {top}." if top else "."), "reputation",
                               speed.get("tool", "Lighthouse"), (speed.get("sources") or [""])[0]))
        acc = (mobile.get("scores") or {}).get("accessibility")
        if acc is not None and acc < 80:
            out.append(Finding("speed.accessibility", "speed", "low", "Accessibility issues on the site",
                               f"Lighthouse accessibility score {acc}/100",
                               "Some visitors can't read or use parts of the site, and it can create legal risk.",
                               "Fix contrast, labels and alt text flagged by Lighthouse.", "reputation",
                               speed.get("tool", "Lighthouse"), (speed.get("sources") or [""])[0]))

    listing = checks.get("listing") or {}
    if listing.get("status") == "ok":
        d = listing["data"]
        place = d.get("place") or {}
        src = (listing.get("sources") or [""])[0]
        tool = listing.get("tool", "Google Maps")
        if not place:
            out.append(Finding("listing.missing", "listing", "high", "We couldn't find your Google Business Profile",
                               f"A Google Maps search for your name in {d.get('search_term', '').split(' ', 1)[-1] or 'your city'} "
                               "didn't open a matching listing.",
                               "Your Google listing is where most local customers find, compare and call you.",
                               "Claim or fix your Google Business Profile so it matches your business name.", "reputation", tool, src))
        rank = d.get("local_rank")
        if place or rank:
            if not rank:
                out.append(Finding("listing.rank", "listing", "high", "You don't show in the local results for your main service",
                                   f'Searching "{d.get("search_term")}" on Google Maps: not in the first {d.get("results_counted")} results.',
                                   "Customers call the businesses they see first. Below the top results you are invisible.",
                                   "Strengthen your Google profile, reviews and local pages for this search.", "reputation", tool, src))
            elif rank > 3:
                out.append(Finding("listing.rank", "listing", "medium", "You're not in the top 3 local results",
                                   f'Searching "{d.get("search_term")}" on Google Maps: you appear at position {rank}.',
                                   "The top 3 get most of the calls from Maps.",
                                   "More recent reviews, a complete profile and matching local pages move you up.", "reputation", tool, src))
        rivals = [c for c in d.get("competitors", [])[:3] if c.get("reviews") is not None]
        if place.get("reviews") is not None and rivals:
            top = max(rivals, key=lambda c: c["reviews"])
            if top["reviews"] > place["reviews"] * 1.5:
                out.append(Finding("listing.reviews", "listing", "high" if top["reviews"] > place["reviews"] * 3 else "medium",
                                   "Competitors have far more Google reviews",
                                   f"You: {place['reviews']} reviews. {top['name']}: {top['reviews']} reviews.",
                                   "Review count is one of the strongest local ranking and trust signals.",
                                   "Ask every finished customer for a review automatically, by text, at the right moment.",
                                   "reputation", tool, src))
        if place.get("rating") is not None and d.get("market_avg_rating") and place["rating"] + 0.2 < d["market_avg_rating"]:
            out.append(Finding("listing.rating", "listing", "medium", "Your rating is below the local average",
                               f"You: {place['rating']} stars. Average of the top local results: {d['market_avg_rating']}.",
                               "Shoppers compare stars side by side in Maps.",
                               "Reply to every review and ask happy customers to post theirs.", "reputation", tool, src))
        grid = d.get("grid_summary")
        if grid and grid.get("points") and grid["top3"] < grid["points"] * 0.5:
            out.append(Finding("listing.grid", "listing", "medium", "You drop out of the top 3 across much of your area",
                               f"Top 3 in {grid['top3']} of {grid['points']} map points checked around your location.",
                               "Customers a few miles away see your competitors first.",
                               "Area pages, reviews that mention towns and a fuller profile widen your reach.", "reputation", tool, src))

    ai = checks.get("ai_mentions") or {}
    if ai.get("status") == "ok" and ai["data"].get("asked"):
        d = ai["data"]
        if d.get("mentioned_in", 0) == 0:
            others = ", ".join(d.get("others_named", [])[:3])
            out.append(Finding("ai.absent", "ai", "medium", "AI assistants don't recommend you",
                               f"Asked {d['asked']} times for local recommendations, the assistant didn't name you"
                               + (f". It named: {others}." if others else "."),
                               "More customers now ask ChatGPT-style assistants who to call. They repeat what the web says about you.",
                               "Build consistent mentions: Google profile, directories, reviews and clear service pages.",
                               "reputation", ai.get("tool", "AI answers"), ""))

    for item in operations_items:
        if item.status in ("fail", "warn"):
            key = "after_hours_op" if item.key == "after_hours" else item.key
            rule = RULES.get(key)
            if rule:
                category, severity, title, why, fix, service = rule
                if item.status == "warn":
                    severity = "medium" if severity == "high" else "low"
                out.append(Finding(f"operations.{item.key}", category, severity, title, f"You told us: \"{item.value}\"",
                                   why, fix, service, "Your answers", ""))
    out.sort(key=lambda f: (SEVERITY_RANK[f.severity], f.category, f.id))
    return out


def revenue_scenario(answers: dict[str, str]) -> dict[str, Any] | None:
    """A labeled scenario, not a measurement. Only built from numbers the prospect gave us."""
    leads = number(answers.get("monthly_leads"))
    job = number(answers.get("avg_job_value"))
    if not leads or not job:
        return None
    close = percent(answers.get("close_rate"))
    close_assumed = close is None
    close = close or (0.2, 0.3)
    miss = (0.10, 0.20)
    low = leads[0] * miss[0] * close[0] * job[0]
    high = leads[1] * miss[1] * close[1] * job[1]
    return {
        "monthly_low": round(low, -1), "monthly_high": round(high, -1),
        "yearly_low": round(low * 12, -2), "yearly_high": round(high * 12, -2),
        "inputs": [
            {"label": "New leads a month", "value": answers["monthly_leads"], "from": "your answer"},
            {"label": "Average job value", "value": answers["avg_job_value"], "from": "your answer"},
            {"label": "Share of leads that slip (missed, slow or never followed up)", "value": "10-20%", "from": "assumption"},
            {"label": "Share of leads that become jobs", "value": answers.get("close_rate") or "20-30%",
             "from": "assumption" if close_assumed else "your answer"},
        ],
        "label": "Scenario, not a measurement. Change any input and the range changes.",
    }


def services_for(findings: list[Finding]) -> list[dict[str, Any]]:
    weight = {"high": 3, "medium": 2, "low": 1}
    totals: dict[str, int] = {}
    reasons: dict[str, list[str]] = {}
    for f in findings:
        totals[f.service] = totals.get(f.service, 0) + weight[f.severity]
        reasons.setdefault(f.service, [])
        if f.title not in reasons[f.service]:
            reasons[f.service].append(f.title)
    ranked = sorted(totals, key=lambda s: -totals[s])
    out = [{"key": s, **SERVICES[s], "because": reasons[s][:3], "weight": totals[s]} for s in ranked]
    if len(out) >= 3 and "ai_transformation" not in totals:
        out.append({"key": "ai_transformation", **SERVICES["ai_transformation"],
                    "because": ["Gaps show up in several areas at once"], "weight": 0})
    return out
