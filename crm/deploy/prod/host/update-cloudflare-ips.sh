#!/usr/bin/env bash
# Opens 443 only to Cloudflare ranges and tells Caddy to trust them. Run as root at setup and monthly (cron).
# Reads Cloudflare's published lists; changes only the "cloudflare-443" firewall rules and the Caddy snippet.
set -euo pipefail
APP_DIR="${APP_DIR:-/opt/kynetic-crm}"
v4="$(curl -fsS https://www.cloudflare.com/ips-v4)"
v6="$(curl -fsS https://www.cloudflare.com/ips-v6)"
[ -n "$v4" ] && [ -n "$v6" ] || { echo "empty Cloudflare range list; leaving rules as they are" >&2; exit 1; }

{
  echo "# Generated by update-cloudflare-ips.sh. Do not edit."
  echo "trusted_proxies static $(echo "$v4" "$v6" | tr '\n' ' ')"
} >"$APP_DIR/cloudflare-ips.caddy.new"
mv "$APP_DIR/cloudflare-ips.caddy.new" "$APP_DIR/cloudflare-ips.caddy"

# Drop old rules for 443, then add the current ranges.
while read -r num; do ufw --force delete "$num"; done < <(ufw status numbered | grep 'cloudflare-443' | sed -E 's/^\[ *([0-9]+)\].*/\1/' | sort -rn)
for net in $v4 $v6; do ufw allow proto tcp from "$net" to any port 443 comment 'cloudflare-443'; done
echo "ok: $(echo "$v4" "$v6" | wc -w) Cloudflare ranges"
